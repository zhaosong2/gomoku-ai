/* tools/build-worker-src.js — 把引擎打包成一段可直接构造 Blob Worker 的源码（M4）
 * 用法： node tools/build-worker-src.js
 * 产出： engine/worker-src.js  →  UMD 挂到 G.WORKER_SRC（字符串）+ G.WORKER_SRC_HASH
 *
 * 为什么要打包成字符串：`file://` 下 Worker 不能直接加载本地脚本（跨源），
 * 但 Blob URL 多数浏览器可用；因此主线程需要**引擎源码文本**来创建 Blob Worker（§34.1）。
 */
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = path.join(__dirname, '..');
// ★ 依赖顺序（UMD：浏览器挂 G.*，Node 走 require）。
//   v3.20 起：① `engine/data/openings.js` 必须进产物（book.js 解析 Renju 记谱要用 OP.R，
//     此前它只在 index.html 里被主线程加载 ⇒ Worker 里 `G.openings` 是 undefined，
//     一旦在 Worker 侧解析 Renju 记谱就会崩——这是**潜伏 bug**，随本次接线一并修掉）；
//   ② v3.22 起开局库数据是 `engine/data/book-tree.js`（**前缀匹配树**，紧凑串约 29 KB；
//      旧的线库 `book-lines.js` 退出产物——树完全覆盖它的能力且多了胜负信息）；
//   ③ `engine/book.js` 必须排在 `engine/search.js` **之前**（think() 要查开局库）。
const FILES = [
  'engine/core.js',
  'engine/patterns.js',
  'engine/rules.js',
  'engine/eval.js',
  'engine/threat.js',
  'engine/operators.js',       // ★ A12 算子化威胁枚举（依赖 patterns/rules/eval/threat；插在 threat 之后）
  'engine/data/openings.js',   // book.js 依赖（26 开局定义 + 8 种对称）
  'engine/data/book-tree.js',  // 开局库数据（§12.4.3 前缀匹配树，RenjuNet 真实对局，packed 紧凑串）
  'engine/book.js',            // 开局库：格式/解析/索引/查询（M8 起也被 record.js 复用解析棋谱）
  'engine/search.js',          // ★ 依赖 book.js（§12.4 开局出招）
  'engine/record.js',          // M8：棋谱数据层（供 analyze）
  'engine/coach.js',           // M8：hint / judge
  'engine/worker-entry.js',
];

const parts = [];
for (const rel of FILES) {
  const src = fs.readFileSync(path.join(ROOT, rel), 'utf8');
  parts.push('/* ===== ' + rel + ' ===== */\n' + src);
}
const bundle = '(function(){\n' + parts.join('\n') + '\n})();\n';

// 安全字符串字面量（JSON.stringify 会转义引号/反斜杠/换行；再处理 U+2028/29 与 </script>）
function lit(s) {
  return JSON.stringify(s)
    .replace(/\u2028/g, '\\u2028')
    .replace(/\u2029/g, '\\u2029')
    .replace(/<\/script/gi, '<\\/script');
}

const hash = crypto.createHash('sha1').update(bundle).digest('hex').slice(0, 16);

const out =
  '/* AUTO-GENERATED by tools/build-worker-src.js —— 请勿手工编辑。\n' +
  ' * 重新生成： node tools/build-worker-src.js\n' +
  ' * 内容 = engine/{core,patterns,rules,eval,threat,search,book,record,coach,worker-entry}.js 拼接，供 Blob Worker 使用。\n' +
  ' */\n' +
  '(function (root) {\n' +
  '  \'use strict\';\n' +
  '  var G = root.G || (root.G = {});\n' +
  '  G.WORKER_SRC_HASH = ' + lit(hash) + ';\n' +
  '  G.WORKER_SRC = ' + lit(bundle) + ';\n' +
  '})(typeof globalThis !== \'undefined\' ? globalThis : this);\n';

const dest = path.join(ROOT, 'engine/worker-src.js');
fs.writeFileSync(dest, out, 'utf8');
console.log('已生成 engine/worker-src.js');
console.log('  hash   : ' + hash);
console.log('  bundle : ' + (bundle.length / 1024).toFixed(1) + ' KB');
console.log('  输出   : ' + (out.length / 1024).toFixed(1) + ' KB（含转义）');
module.exports = { hash, bundle, FILES };
